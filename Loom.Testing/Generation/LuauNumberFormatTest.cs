using Loom.Luau;
using Loom.Testing;

namespace Loom.Testing.Generation;

// Expected values in this file were captured from the real luau.exe interpreter (luau-lang/luau release 0.731),
// not derived from classic Lua "%.14g" semantics, since Luau's own tostring/tonumber diverge from vanilla Lua.
[Collection("Assembly")]
public class LuauNumberFormatTest
{
    [Theory]
    [InlineData(69420.0, "69420")]
    [InlineData(1e100, "1e+100")]
    [InlineData(0.1, "0.1")]
    [InlineData(100.0, "100")]
    [InlineData(1e21, "1e+21")]
    [InlineData(1e20, "100000000000000000000")]
    [InlineData(1e-10, "1e-10")]
    [InlineData(1.5e300, "1.5e+300")]
    [InlineData(123456789012345.0, "123456789012345")]
    [InlineData(0.00001, "0.00001")]
    [InlineData(0.000001, "0.000001")]
    [InlineData(1234567890123456789.0, "1234567890123456800")]
    [InlineData(-0.0, "-0")]
    [InlineData(0.0, "0")]
    [InlineData(-5.5, "-5.5")]
    [InlineData(3.14159265358979, "3.14159265358979")]
    [InlineData(1e-4, "0.0001")]
    [InlineData(9999999999999999.0, "10000000000000000")]
    [InlineData(1e17, "100000000000000000")]
    [InlineData(2.5, "2.5")]
    [InlineData(10.0, "10")]
    [InlineData(1.0, "1")]
    [InlineData(123.456, "123.456")]
    [InlineData(1e15, "1000000000000000")]
    [InlineData(12e19, "120000000000000000000")]
    [InlineData(120.0, "120")]
    [InlineData(1200.0, "1200")]
    [InlineData(5e-6, "0.000005")]
    [InlineData(1.0 / 3.0, "0.3333333333333333")]
    [InlineData(-1e100, "-1e+100")]
    [InlineData(1e300, "1e+300")]
    [InlineData(1e-300, "1e-300")]
    [InlineData(double.NaN, "nan")]
    [InlineData(double.PositiveInfinity, "inf")]
    [InlineData(double.NegativeInfinity, "-inf")]
    public void ToLuauString_MatchesRealLuauInterpreter(double value, string expected) =>
        Assert.Equal(expected, LuauNumberFormat.ToLuauString(value));

    [Theory]
    [InlineData("69420", "69420")]
    [InlineData("1e+100", "1e+100")]
    [InlineData("  0xFF  ", "255")]
    [InlineData("0x1A", "26")]
    [InlineData("  42  ", "42")]
    [InlineData("3.14", "3.14")]
    [InlineData("-3.14", "-3.14")]
    [InlineData("1e10", "10000000000")]
    [InlineData("inf", "inf")]
    [InlineData("-inf", "-inf")]
    [InlineData("nan", "nan")]
    [InlineData("0X10", "16")]
    [InlineData("1.5e-3", "0.0015")]
    [InlineData("0xff", "255")]
    [InlineData("10", "10")]
    [InlineData(".5", "0.5")]
    [InlineData("5.", "5")]
    [InlineData("+5", "5")]
    [InlineData("-0xFF", "-255")]
    [InlineData("-0x10", "-16")]
    [InlineData("+0xFF", "255")]
    [InlineData("0xFFFFFFFF", "4294967295")]
    [InlineData("0x100000000", "4294967296")]
    [InlineData("0xFFFFFFFFFF", "1099511627775")]
    [InlineData("0x7FFFFFFF", "2147483647")]
    [InlineData("0x80000000", "2147483648")]
    [InlineData("-0x1", "-1")]
    [InlineData(" -0x10 ", "-16")]
    [InlineData("0x0", "0")]
    [InlineData("-.5", "-0.5")]
    [InlineData("1E10", "10000000000")]
    [InlineData(" 1e10 ", "10000000000")]
    [InlineData("  0X1a  ", "26")]
    [InlineData("1.", "1")]
    [InlineData(".1e2", "10")]
    [InlineData("1e+5", "100000")]
    [InlineData("1e-5", "0.00001")]
    [InlineData("5  ", "5")]
    [InlineData("  5", "5")]
    public void TryParse_MatchesRealLuauInterpreter(string input, string expected)
    {
        Assert.True(LuauNumberFormat.TryParse(input, out var value));
        Assert.Equal(expected, LuauNumberFormat.ToLuauString(value));
    }

    [Theory]
    [InlineData("  ")]
    [InlineData("")]
    [InlineData("abc")]
    [InlineData("1e")]
    [InlineData("0x")]
    [InlineData("  123abc")]
    [InlineData("1_000")]
    [InlineData(".")]
    [InlineData("5.5.5")]
    [InlineData("  5  6  ")]
    [InlineData("1e+")]
    [InlineData("1e-")]
    [InlineData("-")]
    [InlineData("+")]
    [InlineData("--5")]
    [InlineData("5-")]
    [InlineData("0x-5")]
    [InlineData("0xG")]
    [InlineData("   ")]
    public void TryParse_RejectsMatchingRealLuauInterpreter(string input) => Assert.False(LuauNumberFormat.TryParse(input, out _));
}
